import { getAllRecipes } from "@/data/recipes";

// Built once at build time, so the service worker file changes on every deploy.
export const dynamic = "force-static";

// New value per build; the browser sees a changed /sw.js and updates.
const BUILD_ID = Date.now().toString(36);

function buildServiceWorker(): string {
  const precache = [
    "/",
    "/offline",
    "/manifest.webmanifest",
    "/icons/icon-192.png",
    "/icons/icon-512.png",
    "/icons/icon-maskable-512.png",
    ...getAllRecipes().map((r) => `/recipes/${r.slug}`),
  ];

  // The worker below is plain JS (no imports). Keep backticks and dollar-brace
  // out of it, because it lives inside this template string.
  return `// Shayne's Cookbook service worker. Generated by src/app/sw.js/route.ts.
var BUILD_ID = ${JSON.stringify(BUILD_ID)};
var PRECACHE = ${JSON.stringify(precache)};

// Pages cache is replaced on every build. Static cache survives builds,
// because hashed /_next/static files never change.
var PAGES_CACHE = "cookbook-pages-" + BUILD_ID;
var STATIC_CACHE = "cookbook-static-v1";
var NAV_TIMEOUT_MS = 4000;

function noop() {}

// Only store good, same-origin responses.
function isCacheable(response) {
  return response && response.status === 200 && response.type === "basic";
}

// Store a response; never throw (quota errors must not break a page).
function put(cacheName, key, response) {
  return caches
    .open(cacheName)
    .then(function (cache) { return cache.put(key, response); })
    .catch(noop);
}

// Key for pages: origin + path, without the query string ("/?q=a" -> "/").
function pageKey(url) {
  var u = new URL(url);
  return u.origin + u.pathname;
}

self.addEventListener("install", function (event) {
  event.waitUntil(
    (async function () {
      var cache = await caches.open(PAGES_CACHE);
      for (var i = 0; i < PRECACHE.length; i++) {
        // One failed URL must not abort the install.
        try {
          await cache.add(new Request(PRECACHE[i], { cache: "reload" }));
        } catch (err) {}
      }
      await self.skipWaiting();
    })()
  );
});

self.addEventListener("activate", function (event) {
  event.waitUntil(
    (async function () {
      var names = await caches.keys();
      await Promise.all(
        names
          .filter(function (n) {
            return n.indexOf("cookbook-pages-") === 0 && n !== PAGES_CACHE;
          })
          .map(function (n) { return caches.delete(n); })
      );
      await self.clients.claim();
    })()
  );
});

// Page loads: network first. Use the saved copy if the network is slow or down.
function handleNavigation(event) {
  var request = event.request;
  var key = pageKey(request.url);
  var pending = Promise.resolve();

  var network = fetch(request).then(function (response) {
    if (isCacheable(response)) pending = put(PAGES_CACHE, key, response.clone());
    return response;
  });
  // Keep the worker alive until the fetch and cache write finish.
  event.waitUntil(network.then(function () { return pending; }, noop));

  var timeout = new Promise(function (resolve) {
    setTimeout(function () { resolve(null); }, NAV_TIMEOUT_MS);
  });

  return Promise.race([network, timeout])
    .then(function (response) {
      if (response) return response;
      // Slow network: use the saved page; with none saved, keep waiting.
      return caches.match(key).then(function (cached) { return cached || network; });
    })
    .catch(function () {
      // Network failed: saved page, else the offline page.
      return caches.match(key).then(function (cached) {
        return (
          cached ||
          caches.match(self.location.origin + "/offline") ||
          new Response("You are offline.", { status: 503 })
        );
      });
    });
}

// Static files: cache first. Fill the cache on a miss.
async function handleStatic(request) {
  var cached = await caches.match(request);
  if (cached) return cached;
  var response = await fetch(request);
  if (isCacheable(response)) put(STATIC_CACHE, request, response.clone());
  return response;
}

// Everything else on this site (RSC payloads, images): network first.
// The key is the full URL, because RSC requests differ by query string.
async function handleOther(request) {
  try {
    var response = await fetch(request);
    if (isCacheable(response)) put(PAGES_CACHE, request, response.clone());
    return response;
  } catch (err) {
    var cached = await caches.match(request);
    if (cached) return cached;
    throw err;
  }
}

self.addEventListener("fetch", function (event) {
  var request = event.request;
  if (request.method !== "GET") return;
  if (request.headers.has("range")) return;

  var url = new URL(request.url);
  if (url.origin !== self.location.origin) return; // never touch third parties
  if (url.pathname === "/sw.js") return;

  if (request.mode === "navigate") {
    event.respondWith(handleNavigation(event));
  } else if (
    url.pathname.indexOf("/_next/static/") === 0 ||
    url.pathname.indexOf("/icons/") === 0 ||
    /\\.(woff2?|ttf|otf|eot)$/i.test(url.pathname)
  ) {
    event.respondWith(handleStatic(request));
  } else {
    event.respondWith(handleOther(request));
  }
});
`;
}

export function GET() {
  return new Response(buildServiceWorker(), {
    headers: {
      "Content-Type": "application/javascript; charset=utf-8",
      "Cache-Control": "public, max-age=0, must-revalidate",
      "Service-Worker-Allowed": "/",
    },
  });
}
